// Собирает .docx "Договор купли-продажи транспортного средства" из уже
// распознанных данных. Ничего не выдумывает — просто расставляет по местам
// то, что передали в data.
//
// Структура и формулировки раздела "Заверения и гарантии Продавца" учитывают
// риск оспаривания сделки при банкротстве продавца (гл. III.1 ФЗ №127-ФЗ
// "О несостоятельности (банкротстве)", ст. 61.2, 61.3) и заверения об
// обстоятельствах по ст. 431.2 ГК РФ. Это не заменяет проверку юристом
// конкретной сделки (реестр залогов, ФССП, Федресурс, картотека арбитражных
// дел) — договор лишь фиксирует заверения сторон.

const {
  Document, Packer, Paragraph, TextRun, AlignmentType,
} = require("docx");
const { formatPriceRu } = require("./numberToWordsRu");

function p(text, opts = {}) {
  const { bold, italic, align, spacingAfter = 120 } = opts;
  return new Paragraph({
    alignment: align || AlignmentType.JUSTIFIED,
    spacing: { after: spacingAfter, line: 300 },
    children: [new TextRun({ text, bold, italics: italic, size: 22, font: "Times New Roman" })],
  });
}

function heading(text) {
  return new Paragraph({
    spacing: { after: 160, before: 260, line: 300 },
    children: [new TextRun({ text, bold: true, size: 22, font: "Times New Roman" })],
  });
}

function initials(fio) {
  const parts = (fio || "").trim().split(/\s+/);
  if (parts.length < 2) return fio || "";
  return parts[0] + " " + parts.slice(1).map((w) => w[0] + ".").join(" ");
}

// data ожидается в форме:
// {
//   city, date, price, // price — число (рубли) либо null/undefined, если не указана
//   seller: { fio, dob, pob, passport, issuedBy, issuedDate, deptCode, address },
//   buyer:  { fio, dob, pob, passport, issuedBy, issuedDate, deptCode, address },
//   vehicle: { model, year, vin, plate, color, pts, sts }
// }
function buildDkp(data) {
  const { seller, buyer, vehicle, city, date, price } = data;

  const priceText = price
    ? `${formatPriceRu(price)}.`
    : "____________ (сумма не указана) рублей 00 копеек.";

  const doc = new Document({
    sections: [{
      properties: {},
      children: [
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { after: 320 },
          children: [new TextRun({ text: "ДОГОВОР КУПЛИ-ПРОДАЖИ ТРАНСПОРТНОГО СРЕДСТВА", bold: true, size: 26, font: "Times New Roman" })],
        }),
        new Paragraph({
          spacing: { after: 360 },
          children: [
            new TextRun({ text: `г. ${city || "____________"}`, size: 22, font: "Times New Roman" }),
            new TextRun({ text: "                                                                            ", size: 22, font: "Times New Roman" }),
            new TextRun({ text: date || "____________", size: 22, font: "Times New Roman" }),
          ],
        }),

        p(`${seller.fio}, ${seller.dob} года рождения, место рождения: ${seller.pob}, паспорт гражданина РФ серия и номер ${seller.passport}, выдан ${seller.issuedBy} ${seller.issuedDate}, код подразделения ${seller.deptCode}, зарегистрированный(ая) по адресу: ${seller.address}, именуемый(ая) в дальнейшем «Продавец», с одной стороны, и`),
        p(`${buyer.fio}, ${buyer.dob} года рождения, место рождения: ${buyer.pob}, паспорт гражданина РФ серия и номер ${buyer.passport}, выдан ${buyer.issuedBy} ${buyer.issuedDate}, код подразделения ${buyer.deptCode}, зарегистрированный(ая) по адресу: ${buyer.address}, именуемый(ая) в дальнейшем «Покупатель», с другой стороны,`),
        p("совместно именуемые «Стороны», заключили настоящий договор о нижеследующем:"),

        heading("1. ПРЕДМЕТ ДОГОВОРА"),
        p(`1.1. Продавец передаёт в собственность, а Покупатель принимает и оплачивает транспортное средство: ${vehicle.model}, ${vehicle.year} года выпуска, идентификационный номер (VIN) ${vehicle.vin}, государственный регистрационный знак ${vehicle.plate}, цвет кузова: ${vehicle.color} (далее — «ТС»).`),
        p(`1.2. Документы на транспортное средство: паспорт транспортного средства (ПТС) ${vehicle.pts}; свидетельство о регистрации транспортного средства (СТС) ${vehicle.sts}.`),
        p("1.3. Продавец гарантирует, что является единственным законным собственником ТС и обладает полным и безусловным правом на его отчуждение."),

        heading("2. ЦЕНА ДОГОВОРА И ПОРЯДОК РАСЧЁТОВ"),
        p(`2.1. Стоимость транспортного средства составляет ${priceText}`),
        p("2.2. Стороны подтверждают, что цена, указанная в п. 2.1, соответствует рыночной стоимости транспортного средства на дату заключения настоящего договора, определена по свободному волеизъявлению Сторон и не является заниженной."),
        p("2.3. Расчёт между Сторонами произведён полностью до подписания настоящего договора. Претензий по оплате Стороны друг к другу не имеют."),

        heading("3. ПРАВА И ОБЯЗАННОСТИ СТОРОН"),
        p("3.1. Продавец обязан передать Покупателю ТС и относящиеся к нему документы, указанные в п. 1.2, в состоянии, пригодном для использования по назначению, свободным от прав третьих лиц."),
        p("3.2. Покупатель обязан принять ТС и уплатить цену, указанную в разделе 2 настоящего договора."),
        p("3.3. С момента подписания настоящего договора и акта приёма-передачи Покупатель вправе владеть, пользоваться и распоряжаться ТС по своему усмотрению."),

        heading("4. ЗАВЕРЕНИЯ И ГАРАНТИИ ПРОДАВЦА"),
        p("4.1. Продавец заверяет и гарантирует Покупателю (ст. 431.2 ГК РФ), что на момент заключения настоящего договора:"),
        p("— ТС никому другому не продано, не подарено, не заложено, в споре и под арестом (запрещением) не состоит, не является предметом судебного разбирательства, свободно от любых прав и притязаний третьих лиц;"),
        p("— Продавец не отвечает признакам неплатёжеспособности и (или) недостаточности имущества в значении, придаваемом ст. 2 Федерального закона от 26.10.2002 № 127-ФЗ «О несостоятельности (банкротстве)»;"),
        p("— в отношении Продавца не возбуждено производство по делу о банкротстве, заявление о признании Продавца банкротом не подано ни самим Продавцом, ни его кредиторами, ни уполномоченным органом;"),
        p("— у Продавца отсутствуют неисполненные более трёх месяцев обязательства перед третьими лицами, дающие основания для возбуждения в отношении него дела о банкротстве;"),
        p("— настоящая сделка совершается добровольно, по справедливой рыночной цене, не направлена на причинение вреда имущественным правам кредиторов Продавца и не имеет целью вывод имущества (ст. 61.2, 61.3 Федерального закона № 127-ФЗ).", { spacingAfter: 160 }),
        p("4.2. Покупатель заверяет, что не является лицом, заинтересованным по отношению к Продавцу (не состоит с ним в родстве, свойстве, трудовых или корпоративных отношениях), приобретает ТС добросовестно, не осведомлён и не мог быть осведомлён о каких-либо обстоятельствах, свидетельствующих о признаках неплатёжеспособности Продавца либо о цели причинения вреда его кредиторам."),
        p("4.3. Сторона, предоставившая недостоверные заверения по настоящему разделу, обязана возместить другой Стороне убытки, причинённые недостоверностью таких заверений (п. 1 ст. 431.2 ГК РФ)."),

        heading("5. ОТВЕТСТВЕННОСТЬ СТОРОН"),
        p("5.1. За неисполнение или ненадлежащее исполнение обязательств по настоящему договору Стороны несут ответственность в соответствии с действующим законодательством Российской Федерации."),
        p("5.2. В случае признания настоящего договора недействительным по основаниям, предусмотренным главой III.1 Федерального закона № 127-ФЗ «О несостоятельности (банкротстве)» (в том числе по ст. 61.2, 61.3), Продавец обязуется возместить Покупателю в полном объёме уплаченную по договору стоимость ТС, документально подтверждённые расходы Покупателя на содержание, ремонт и страхование ТС за период владения, а также понесённые Покупателем судебные расходы."),

        heading("6. ПОРЯДОК ПЕРЕДАЧИ ТРАНСПОРТНОГО СРЕДСТВА"),
        p("6.1. Продавец передаёт Покупателю транспортное средство, комплект ключей и документы, указанные в п. 1.2, в момент подписания настоящего договора."),
        p("6.2. Настоящий договор одновременно является актом приёма-передачи транспортного средства и подтверждает отсутствие взаимных претензий Сторон по техническому состоянию и комплектности транспортного средства."),

        heading("7. РАЗРЕШЕНИЕ СПОРОВ"),
        p("7.1. Все споры и разногласия, возникающие из настоящего договора или в связи с ним, Стороны разрешают путём переговоров, а при недостижении согласия — в судебном порядке в соответствии с действующим законодательством Российской Федерации."),

        heading("8. ПРОЧИЕ УСЛОВИЯ"),
        p("8.1. Настоящий договор составлен в двух экземплярах, имеющих одинаковую юридическую силу, по одному экземпляру для каждой из Сторон."),
        p("8.2. Договор вступает в силу с момента подписания Сторонами и действует до полного исполнения Сторонами своих обязательств.", { spacingAfter: 420 }),

        heading("9. АДРЕСА И ПОДПИСИ СТОРОН"),

        p("ПРОДАВЕЦ:", { bold: true, spacingAfter: 60 }),
        p(seller.fio, { spacingAfter: 20 }),
        p(`Паспорт: ${seller.passport}, выдан ${seller.issuedBy} ${seller.issuedDate}, код подразделения ${seller.deptCode}`, { spacingAfter: 20 }),
        p(`Адрес регистрации: ${seller.address}`, { spacingAfter: 20 }),
        p(`Подпись: _________________________ / ${initials(seller.fio)} /`, { spacingAfter: 380 }),

        p("ПОКУПАТЕЛЬ:", { bold: true, spacingAfter: 60 }),
        p(buyer.fio, { spacingAfter: 20 }),
        p(`Паспорт: ${buyer.passport}, выдан ${buyer.issuedBy} ${buyer.issuedDate}, код подразделения ${buyer.deptCode}`, { spacingAfter: 20 }),
        p(`Адрес регистрации: ${buyer.address}`, { spacingAfter: 20 }),
        p(`Подпись: _________________________ / ${initials(buyer.fio)} /`, { spacingAfter: 20 }),
      ],
    }],
  });

  return Packer.toBuffer(doc);
}

module.exports = { buildDkp };
